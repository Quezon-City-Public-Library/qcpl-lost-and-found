// One-time helper: downloads the site's Google Fonts (SIL Open Font License)
// into assets/fonts/ and writes css/fonts.css so the site needs no internet.
// Usage: node tools/fetch-fonts.mjs
import { mkdir, writeFile } from "node:fs/promises";

const CSS_URL = "https://fonts.googleapis.com/css2?family=Inter:wght@100..900&display=swap";
const KEEP = new Set(["latin", "latin-ext"]);
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

const css = await (await fetch(CSS_URL, { headers: { "User-Agent": UA } })).text();
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g)];
await mkdir("assets/fonts", { recursive: true });

let out = "/* Local copies of Inter (the font used on qcpl.quezoncity.gov.ph) (SIL Open Font License). Generated by tools/fetch-fonts.mjs */\n";
for (const [, subset, block] of blocks) {
  if (!KEEP.has(subset)) continue;
  const family = block.match(/font-family:\s*'([^']+)'/)[1];
  const weight = block.match(/font-weight:\s*(\d+)/)[1];
  const url = block.match(/url\(([^)]+)\)/)[1];
  const style = /font-style:\s*italic/.test(block) ? "-italic" : "";
  const file = `${family.replace(/\s+/g, "")}-${weight}${style}-${subset}.woff2`;
  await writeFile(`assets/fonts/${file}`, Buffer.from(await (await fetch(url)).arrayBuffer()));
  out += `/* ${subset} */\n` + block.replace(/url\([^)]+\)/, `url("../assets/fonts/${file}")`) + "\n";
  console.log("saved", file);
}
await writeFile("css/fonts.css", out);
console.log("wrote css/fonts.css");
