// One-time helper: downloads the MobileNet v2 image-recognition model
// (Apache-2.0, Google / TF Hub) and the TensorFlow.js library into assets/ai/,
// then packs the model into one script file so photo recognition works
// offline — even when index.html is opened straight from a folder.
// Usage: node tools/fetch-ai-model.mjs [050|075|100]   (default 075)
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { createRequire } from "node:module";

const size = process.argv[2] || "075";
const BASE = `https://tfhub.dev/google/imagenet/mobilenet_v2_${size}_224/classification/2`;
const get = async (url, tries = 5) => {
  for (let i = 1; ; i++) {
    try {
      const res = await fetch(url, { redirect: "follow" });
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      return res;
    } catch (err) {
      if (i >= tries) throw err;
      await new Promise((r) => setTimeout(r, 1500 * i)); // network hiccup — wait and retry
    }
  }
};

await mkdir("assets/ai", { recursive: true });
const modelJson = await (await get(`${BASE}/model.json?tfjs-format=file`)).json();
const paths = modelJson.weightsManifest.flatMap((g) => g.paths);
const parts = [];
for (const p of paths) {
  parts.push(Buffer.from(await (await get(`${BASE}/${p}?tfjs-format=file`)).arrayBuffer()));
  process.stdout.write(".");
}
const raw = Buffer.concat(parts);
const specs = modelJson.weightsManifest.flatMap((g) => g.weights);

// Store float32 weights as float16 (half the size, same predictions in practice)
function toHalf(f) {
  const f32 = new Float32Array([f]), u32 = new Uint32Array(f32.buffer)[0];
  const sign = (u32 >> 16) & 0x8000, exp = ((u32 >> 23) & 0xff) - 127 + 15, mant = u32 & 0x7fffff;
  if (exp <= 0) return exp < -10 ? sign : sign | ((mant | 0x800000) >> (1 - exp + 13));
  if (exp >= 31) return sign | 0x7c00;
  return sign | (exp << 10) | (mant >> 13);
}
const out = [];
let offset = 0;
for (const s of specs) {
  const count = s.shape.reduce((a, b) => a * b, 1);
  const bytes = s.quantization ? count * { uint8: 1, uint16: 2, float16: 2 }[s.quantization.dtype] : count * 4;
  const chunk = raw.subarray(offset, offset + bytes);
  offset += bytes;
  if (s.dtype === "float32" && !s.quantization) {
    const half = Buffer.alloc(count * 2);
    for (let i = 0; i < count; i++) half.writeUInt16LE(toHalf(chunk.readFloatLE(i * 4)), i * 2);
    s.quantization = { dtype: "float16" };
    out.push(half);
  } else out.push(chunk);
}
if (offset !== raw.length) throw new Error("Unexpected weight layout");
const weights = Buffer.concat(out);
// One manifest group pointing at a single combined weights blob
modelJson.weightsManifest = [{ paths: ["weights.bin"], weights: specs }];

await writeFile("assets/ai/mobilenet-model.js",
  `/* MobileNet v2 (${size}) ImageNet classifier — Apache-2.0, Google. Generated by tools/fetch-ai-model.mjs */\n` +
  `window.MOBILENET_MODEL = { json: ${JSON.stringify(modelJson)}, weights: "${weights.toString("base64")}" };\n`);

// TensorFlow.js library (Apache-2.0)
const require = createRequire(import.meta.url);
const tfPath = process.env.TFJS_PATH || require.resolve("@tensorflow/tfjs/dist/tf.min.js");
await writeFile("assets/ai/tf.min.js", await readFile(tfPath));
console.log(`\nSaved assets/ai/mobilenet-model.js (${(weights.length / 1048576).toFixed(1)} MB of weights) and assets/ai/tf.min.js`);
